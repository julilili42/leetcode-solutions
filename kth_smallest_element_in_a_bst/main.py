# Change this to the LeetCode method name
METHOD = "kthSmallest"


class Solution:
    def kthSmallest(self, root: TreeNode | None, k: int) -> int:
        i = 0
        res = None

        def dfs(node):
            nonlocal res, i
            if not node or res is not None:
                return

            dfs(node.left)
            i += 1
            if i == k:
                res = node.val
            dfs(node.right)

        dfs(root)
        return res


